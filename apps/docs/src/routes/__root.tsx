import config from 'virtual:tanstack-blog/config'
import searchData from 'virtual:tanstack-blog/search-data'
import { createThemeCss } from '@tanstack/highlight/theme'
import { githubDarkTheme } from '@tanstack/highlight/themes/github-dark'
import { githubLightTheme } from '@tanstack/highlight/themes/github-light'
import { createRootRoute, HeadContent, Scripts, useRouter } from '@tanstack/react-router'
import { useStore } from '@tanstack/react-store'
import { createAlgoliaSearchAdapter } from '@tanstack-blog/algolia-search'
import { createTranslator, switchLocaleRoute, switchVersionRoute } from '@tanstack-blog/core'
import { createOramaSearchAdapter } from '@tanstack-blog/orama-search'
import { createLocalSearchAdapter } from '@tanstack-blog/search'
import { allThemes } from '@tanstack-blog/themes'
import {
  ClientNav,
  ReadingProgress,
  SlotsProvider,
  ThemeProvider,
  themeInitScript,
  useSlots,
} from '@tanstack-blog/ui'
import { store } from '../app-state.js'
import { themeSlots } from '../theme.config.js'
import '@tanstack-blog/ui/styles.css'

/** Search is a swappable package, not part of core. */
const searchAdapter =
  config.search.provider === 'orama'
    ? createOramaSearchAdapter(searchData)
    : config.search.provider === 'algolia' && config.search.algolia
      ? createAlgoliaSearchAdapter(config.search.algolia)
      : createLocalSearchAdapter(searchData)

/** Highlight token CSS generated by TanStack Highlight, scoped to rendered Markdown. */
const highlightCss = createThemeCss({
  light: githubLightTheme,
  dark: githubDarkTheme,
  lightSelector: '.tb-markdown',
  darkSelector: '.dark .tb-markdown',
  codeBlockSelector: '.tb-markdown pre.tm-code',
  lineNumbersSelector: '.tb-markdown .tm-code--line-numbers',
})

/** Static, framework-generated content. Kept outside JSX to avoid unsafe-inline lint noise. */
const staticBootScript = {
  dangerouslySetInnerHTML: {
    __html: themeInitScript('system', config.theme.storeKey, allThemes, config.theme.default),
  },
}
/** Apply a custom theme created in the editor before hydration. */
const customThemeBootScript = {
  dangerouslySetInnerHTML: {
    __html: `(function(){try{var t=JSON.parse(localStorage.getItem('tb:custom-theme')||'null');if(!t||!t.light||!t.dark)return;var s=JSON.parse(localStorage.getItem(${JSON.stringify(config.theme.storeKey)})||'null')||{};var m=s.mode||'system';var r=m==='system'?(matchMedia('(prefers-color-scheme: dark)').matches?'dark':'light'):m;var tokens=t[r]||t.light;for(var k in tokens)document.documentElement.style.setProperty(k,tokens[k]);document.documentElement.dataset.theme=t.id}catch(e){}})()`,
  },
}

/** Redirect unprefixed URLs to the persisted locale before the app boots. */
const localeBootScript = {
  dangerouslySetInnerHTML: {
    __html: `(function(){try{var k=${JSON.stringify(config.theme.storeKey)};var s=JSON.parse(localStorage.getItem(k)||'null');var l=s&&s.locale;var d=${JSON.stringify(config.i18n.defaultLocale)};var p=location.pathname;if(l&&l!==d&&!new RegExp('^/'+l+'($|/)').test(p)){location.replace('/'+l+(p==='/'?'':p)+location.search+location.hash)}}catch(e){}})()`,
  },
}

const highlightStyle = {
  dangerouslySetInnerHTML: { __html: highlightCss },
}

/** Optional analytics providers; custom stays data-hook only. */
function analyticsScripts(): Array<Record<string, unknown>> {
  const provider = config.analytics.provider
  const domain = config.analytics.domain ?? ''
  if (provider === 'plausible' && domain) {
    return [
      {
        children: `window.plausible=window.plausible||function(){(window.plausible.q=window.plausible.q||[]).push(arguments)}`,
      },
      { src: 'https://plausible.io/js/script.js', defer: true, 'data-domain': domain },
    ]
  }
  if (provider === 'umami' && domain) {
    return [{ src: 'https://cloud.umami.is/script.js', defer: true, 'data-website-id': domain }]
  }
  return []
}

export const Route = createRootRoute({
  head: () => ({
    meta: [
      { charSet: 'utf-8' },
      { name: 'viewport', content: 'width=device-width, initial-scale=1' },
      { title: `${config.title} — ${config.description}` },
      { name: 'description', content: config.description },
      { property: 'og:title', content: config.title },
      { property: 'og:description', content: config.description },
      { name: 'theme-color', content: '#08090a' },
    ],
    links: [
      ...(config.siteUrl ? [{ rel: 'canonical', href: config.siteUrl }] : []),
      ...(config.analytics.provider === 'plausible' && config.analytics.domain
        ? [
            {
              rel: 'preconnect',
              href: 'https://plausible.io',
            },
          ]
        : []),
    ],
    scripts: analyticsScripts(),
  }),
  shellComponent: RootDocument,
})

function RootDocument({ children }: { children: React.ReactNode }) {
  return (
    <html lang={config.i18n.defaultLocale} suppressHydrationWarning>
      <head>
        <script {...customThemeBootScript} />
        <script {...localeBootScript} />
        <script {...staticBootScript} />
        <style {...highlightStyle} />
        <HeadContent />
      </head>
      <body
        data-analytics={config.analytics.provider}
        data-analytics-domain={config.analytics.domain}
      >
        {/* dumi-style slot layer: custom themes override individual components. */}
        <SlotsProvider slots={themeSlots}>
          <AppChrome>{children}</AppChrome>
        </SlotsProvider>
        <Scripts />
      </body>
    </html>
  )
}

/** Chrome consumes resolved slots so a theme can replace any single element. */
function AppChrome({ children }: { children: React.ReactNode }) {
  const router = useRouter()
  const { Header, Footer, SearchDialog, BackToTop } = useSlots()
  const activeLocale = useStore(store, (state) => state.locale)
  const t = createTranslator(activeLocale)
  const navigate = (route: string) => void router.navigate({ to: route as never })
  const onLocaleChange = (locale: string) => {
    store.setState((state) => ({ ...state, locale }))
    navigate(switchLocaleRoute(config, window.location.pathname, locale))
  }
  const onVersionChange = (version: string) => {
    store.setState((state) => ({ ...state, version }))
    navigate(
      switchVersionRoute(
        window.location.pathname,
        version,
        config.currentVersion,
        config.i18n.locales.map((item) => item.code),
      ),
    )
  }

  return (
    <ThemeProvider store={store} themes={allThemes} storageKey={config.theme.storeKey}>
      <ReadingProgress />
      <a className="tb-skip-link" href="#site-main-content">
        {t('a11y.skip')}
      </a>
      <ClientNav store={store} config={config} />
      <BackToTop />
      <div className="tb-app">
        <Header
          store={store}
          config={config}
          themes={allThemes}
          locales={config.i18n.locales}
          t={t}
          onLocaleChange={onLocaleChange}
          versions={config.versions}
          currentVersion={config.currentVersion}
          onVersionChange={onVersionChange}
        />
        <div className="tb-app-body" id="site-main-content">
          {children}
        </div>
        <Footer config={config} t={t} />
      </div>
      {config.search.provider !== 'none' ? (
        <SearchDialog
          store={store}
          adapter={searchAdapter}
          config={config}
          t={t}
          onNavigate={navigate}
        />
      ) : null}
    </ThemeProvider>
  )
}
