import config from 'virtual:tanstack-blog/config'
import searchData from 'virtual:tanstack-blog/search-data'
import { createThemeCss } from '@tanstack/highlight/theme'
import { githubDarkTheme } from '@tanstack/highlight/themes/github-dark'
import { githubLightTheme } from '@tanstack/highlight/themes/github-light'
import { createRootRoute, HeadContent, Scripts, useRouter } from '@tanstack/react-router'
import { switchLocaleRoute } from '@tanstack-blog/core'
import { createOramaSearchAdapter } from '@tanstack-blog/orama-search'
import { createLocalSearchAdapter } from '@tanstack-blog/search'
import { allThemes } from '@tanstack-blog/themes'
import {
  BackToTop,
  ClientNav,
  SearchDialog,
  SiteFooter,
  SiteHeader,
  ThemeProvider,
  themeInitScript,
} from '@tanstack-blog/ui'
import '@tanstack-blog/ui/styles.css'

import { store, t } from '../app-state.js'

/** Search is a swappable package, not part of core. */
const searchAdapter =
  config.search.provider === 'orama'
    ? createOramaSearchAdapter(searchData)
    : createLocalSearchAdapter(searchData)

/** Highlight token CSS generated by TanStack Highlight, scoped to rendered Markdown. */
const highlightCss = createThemeCss({
  light: githubLightTheme,
  dark: githubDarkTheme,
  lightSelector: '.tb-markdown',
  darkSelector: '.dark .tb-markdown',
  codeBlockSelector: '.tb-markdown pre.tm-code',
  lineNumbersSelector: '.tb-markdown .tm-code--line-numbers',
})

/** Static, framework-generated content. Kept outside JSX to avoid unsafe-inline lint noise. */
const staticBootScript = {
  dangerouslySetInnerHTML: {
    __html: themeInitScript('system', config.theme.storeKey, allThemes, config.theme.default),
  },
}
const highlightStyle = {
  dangerouslySetInnerHTML: { __html: highlightCss },
}

export const Route = createRootRoute({
  head: () => ({
    meta: [
      { charSet: 'utf-8' },
      { name: 'viewport', content: 'width=device-width, initial-scale=1' },
      { title: `${config.title} — ${config.description}` },
      { name: 'description', content: config.description },
      { property: 'og:title', content: config.title },
      { property: 'og:description', content: config.description },
      { name: 'theme-color', content: '#08090a' },
    ],
    links: config.siteUrl ? [{ rel: 'canonical', href: config.siteUrl }] : [],
  }),
  shellComponent: RootDocument,
})

function RootDocument({ children }: { children: React.ReactNode }) {
  const router = useRouter()
  const navigate = (route: string) => void router.navigate({ to: route as never })

  const onLocaleChange = (locale: string) => {
    store.setState((state) => ({ ...state, locale }))
    navigate(switchLocaleRoute(config, window.location.pathname, locale))
  }

  return (
    <html lang={config.i18n.defaultLocale} suppressHydrationWarning>
      <head>
        <script {...staticBootScript} />
        <style {...highlightStyle} />
        <HeadContent />
      </head>
      <body
        data-analytics={config.analytics.provider}
        data-analytics-domain={config.analytics.domain}
      >
        <ThemeProvider store={store} themes={allThemes} storageKey={config.theme.storeKey}>
          <ClientNav />
          <BackToTop />
          <div className="tb-app">
            <SiteHeader
              store={store}
              config={config}
              themes={allThemes}
              locales={config.i18n.locales}
              t={t}
              onLocaleChange={onLocaleChange}
            />
            <div className="tb-app-body">{children}</div>
            <SiteFooter config={config} t={t} />
          </div>
          {config.search.provider !== 'none' ? (
            <SearchDialog
              store={store}
              adapter={searchAdapter}
              config={config}
              t={t}
              onNavigate={navigate}
            />
          ) : null}
        </ThemeProvider>
        <Scripts />
      </body>
    </html>
  )
}
