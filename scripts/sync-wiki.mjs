#!/usr/bin/env node
/**
 * Mirror the documentation Markdown into a GitHub-wiki-friendly directory.
 * Idempotent: files not produced by this script are left untouched.
 */
import { promises as fs } from 'node:fs'
import path from 'node:path'

const ROOT = process.cwd()
const SOURCE = path.join(ROOT, 'apps/docs/content')
const TARGET = path.join(ROOT, 'wiki')

async function walk(dir) {
  const entries = await fs.readdir(dir, { withFileTypes: true })
  const files = []
  for (const entry of entries) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) files.push(...(await walk(full)))
    else if (entry.name.endsWith('.md')) files.push(full)
  }
  return files
}

async function main() {
  await fs.mkdir(TARGET, { recursive: true })
  const files = await walk(SOURCE)
  let written = 0

  for (const file of files) {
    const relative = path.relative(SOURCE, file).split(path.sep).join('/')
    const raw = await fs.readFile(file, 'utf8')
    if (/^---[\s\S]*?^draft:\s*true/m.test(raw)) continue

    const segments = relative.split('/')
    const locale = segments.length > 1 && segments[0].includes('-') ? segments.shift() : 'en'
    const outName = `${segments.join('--').replace(/\.md$/, '')}.md`
    const outFile = path.join(TARGET, locale, outName)
    const note = `<!-- Mirrored from apps/docs/content/${relative}. Edit the source, not this file. -->\n\n`

    await fs.mkdir(path.dirname(outFile), { recursive: true })
    await fs.writeFile(outFile, `${note}${raw}`, 'utf8')
    written += 1
  }

  const homeSource = path.join(SOURCE, 'en/index.md')
  const home = await fs.readFile(homeSource, 'utf8')
  await fs.writeFile(
    path.join(TARGET, 'Home.md'),
    `<!-- Generated by scripts/sync-wiki.mjs -->\n\n${home}`,
    'utf8',
  )

  console.log(`wiki:sync wrote ${written} pages + Home.md to ${path.relative(ROOT, TARGET)}`)
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
